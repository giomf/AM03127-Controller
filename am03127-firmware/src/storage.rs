/// Logger name for storage-related log messages
const LOGGER_NAME: &str = "NvsStorage";
// PAGE_STORAGE_BEGIN/SIZE and SCHEDULE_STORAGE_BEGIN/SIZE: the two halves of the `nvs`
// partition in partition-table.csv, generated by build.rs.
include!(concat!(env!("OUT_DIR"), "/storage_layout.rs"));

/// Stored with postcard, the same format the earlier hand-written `Value` impls used.
#[derive(Serialize, Deserialize, Debug, Clone)]
pub struct PageWrapper(pub Page);
impl PostcardValue<'_> for PageWrapper {}
impl From<Page> for PageWrapper {
    fn from(page: Page) -> Self {
        PageWrapper(page)
    }
}

#[derive(Serialize, Deserialize, Debug, Clone)]
pub struct ScheduleWrapper(pub Schedule);
impl PostcardValue<'_> for ScheduleWrapper {}
impl From<Schedule> for ScheduleWrapper {
    fn from(schedule: Schedule) -> Self {
        ScheduleWrapper(schedule)
    }
}

/// Storage section for persistent data in flash memory
///
/// This generic struct provides methods to read, write, and delete items
/// from a specific section of flash memory.
pub struct NvsStorageSection<T, const S: usize> {
    /// Flash storage driver
    flash: SharedStorage,
    /// Range of flash memory addresses for this section
    flash_range: Range<u32>,
    /// Phantom data to track the type stored in this section
    _type: PhantomData<T>,
}

impl<T: for<'a> Value<'a> + Clone + Debug, const S: usize> NvsStorageSection<T, S> {
    /// A map over this section on the locked flash. sequential-storage owns its flash, so
    /// each operation borrows the shared flash only for its duration.
    fn map<'f>(
        &self,
        flash: &'f mut FlashStorage<'static>,
    ) -> MapStorage<u8, BlockingAsync<&'f mut FlashStorage<'static>>, impl CacheImpl<u8>> {
        MapStorage::new(
            BlockingAsync::new(flash),
            MapConfig::new(self.flash_range.clone()),
            Cache::new_uncached(),
        )
    }

    /// Creates a new storage section in flash memory
    ///
    /// # Arguments
    /// * `flash_begin` - Starting address of the flash section
    /// * `flash_size` - Size of the flash section in bytes
    ///
    /// # Returns
    /// * A new NvsStorageSection instance
    pub fn new(flash_storage: SharedStorage, flash_begin: u32, flash_size: u32) -> Self {
        let flash_end = flash_begin + flash_size;
        let flash_range = flash_begin..flash_end;

        NvsStorageSection {
            flash: flash_storage,
            flash_range,
            _type: PhantomData,
        }
    }

    /// Reads an item from storage by its key
    ///
    /// # Arguments
    /// * `key` - Character key to identify the item
    ///
    /// # Returns
    /// * `Ok(Some(T))` - The item if found
    /// * `Ok(None)` - If the item doesn't exist
    /// * `Err(Error)` - If reading failed
    pub async fn read(&self, key: char) -> Result<Option<T>, Error> {
        log::info!("{LOGGER_NAME}: Reading \"{key}\"");

        let mut data_buffer = [0; S];
        let flash = &mut *self.flash.lock().await;

        let value = self
            .map(flash)
            .fetch_item::<Option<T>>(&mut data_buffer, &(key as u8))
            .await?;

        match value {
            Some(value) => {
                log::debug!("{LOGGER_NAME}: read {:?}", value);
                Ok(value)
            }
            None => Ok(None),
        }
    }

    /// Reads all items from storage
    ///
    /// # Type Parameters
    /// * `N` - Maximum number of items to read
    ///
    /// # Returns
    /// * `Ok(Vec<T, N>)` - Vector of all items
    /// * `Err(Error)` - If reading failed
    pub async fn read_all(&self) -> Result<Vec<T>, Error> {
        log::info!("{LOGGER_NAME}: Reading all");

        let mut data_buffer = [0; S];
        let flash = &mut *self.flash.lock().await;
        let mut map = self.map(flash);

        let mut item_iterator = map.fetch_all_items(&mut data_buffer).await?;

        let mut values = BTreeMap::new();
        while let Some((key, item)) = item_iterator.next::<Option<T>>(&mut data_buffer).await? {
            values.insert(key, item);
        }

        Ok(values.into_values().flatten().collect())
    }

    /// Writes an item to storage
    ///
    /// # Arguments
    /// * `key` - Character key to identify the item
    /// * `value` - The item to write
    ///
    /// # Returns
    /// * `Ok(())` - If writing was successful
    /// * `Err(Error)` - If writing failed
    pub async fn write(&self, key: char, value: T) -> Result<(), Error> {
        log::info!("{LOGGER_NAME}: Writing \"{key}\"");

        let mut data_buffer = [0; S];
        let flash = &mut *self.flash.lock().await;

        self.map(flash)
            .store_item(&mut data_buffer, &(key as u8), &Some(value))
            .await?;

        Ok(())
    }

    /// Deletes an item from storage
    ///
    /// # Arguments
    /// * `key` - Character key identifying the item to delete
    ///
    /// # Returns
    /// * `Ok(())` - If deletion was successful
    /// * `Err(Error)` - If deletion failed
    pub async fn delete(&self, key: char) -> Result<(), Error> {
        log::info!("{LOGGER_NAME}: Deleting \"{key}\"");

        // Stored as `None` (not removed) to keep the on-flash format of earlier versions.
        let mut data_buffer = [0; S];
        let flash = &mut *self.flash.lock().await;

        self.map(flash)
            .store_item::<Option<T>>(&mut data_buffer, &(key as u8), &None)
            .await?;

        Ok(())
    }

    pub async fn delete_all(&self) -> Result<(), Error> {
        log::info!("{LOGGER_NAME}: Deleting all");
        let flash = &mut *self.flash.lock().await;
        self.map(flash).erase_all().await?;
        Ok(())
    }
}
